function qc = avde_session_qc(session, cfg)
% QC summary stored in the final file and printed at the end: inter-game AND
% within-game timing, and response-quality counts.
S = session.gameSummaries; done = strcmp({S.slotStatus},'completed');
ig = [S.interGameEndToFirstFaceSeconds]; ig = ig(isfinite(ig));
E = repmat(avde_empty_event(),0,1);
for g = 1:numel(session.gameLogs); if ~isempty(session.gameLogs{g}); E = [E; session.gameLogs{g}(:)]; end; end %#ok<AGROW>
oe = [E.onsetError]; oe = oe(isfinite(oe));
fc = E(strcmp({E.eventType},'free_choice')); jo = E(strcmp({E.eventType},'joint_outcome'));
delay = [];
for i = 1:numel(jo)
    k = find([fc.game]==jo(i).game & [fc.freeTrial]==jo(i).freeTrial, 1);
    if ~isempty(k) && isfinite(fc(k).responseTime); delay(end+1) = jo(i).actualOnset - fc(k).responseTime; end %#ok<AGROW>
end
qc = struct('nCompleted',sum(done),'nAborted',sum(strncmp({S.slotStatus},'aborted',7)), ...
    'interGameN',numel(ig),'interGameMean',local_m(ig),'interGameMax',local_x(ig), ...
    'interGameTarget',cfg.timing.interGameEndToFirstFace,'nLateTransitions',sum([S.interGameLate]), ...
    'nFlips',numel(oe),'nMissedFrames',sum([E.missedFrame]),'onsetErrorMedian',local_med(oe),'onsetErrorMax',local_x(oe), ...
    'responseToOutcomeMedian',local_med(delay),'responseToOutcomeMax',local_x(delay), ...
    'nChoices',numel(fc),'nTimeouts',sum([fc.timeout]),'nFastResponses',sum([fc.fastResponse]), ...
    'nAnticipatory',sum([fc.anticipatoryPress]),'nSimultaneous',sum([fc.simultaneousPress]),'nHeldAtOnset',sum([fc.keyHeldAtOnset]), ...
    'breaks',numel(session.breakLog),'resumes',numel(session.resumeLog));
if cfg.debug.verbose
    fprintf(['QC: %d completed, %d aborted | end->first face mean %.4f s, max %.4f s (target %.3f), %d late | ' ...
        '%d flips, %d missed frames, onset error median %.4f s, max %.4f s | response->outcome median %.4f s, max %.4f s | ' ...
        '%d choices: %d timeouts, %d fast, %d anticipatory, %d simultaneous, %d held\n'], qc.nCompleted, qc.nAborted, ...
        qc.interGameMean, qc.interGameMax, qc.interGameTarget, qc.nLateTransitions, qc.nFlips, qc.nMissedFrames, ...
        qc.onsetErrorMedian, qc.onsetErrorMax, qc.responseToOutcomeMedian, qc.responseToOutcomeMax, ...
        qc.nChoices, qc.nTimeouts, qc.nFastResponses, qc.nAnticipatory, qc.nSimultaneous, qc.nHeldAtOnset);
end
end
function m = local_m(x); if isempty(x); m = NaN; else; m = mean(x); end; end
function m = local_x(x); if isempty(x); m = NaN; else; m = max(x); end; end
function m = local_med(x); if isempty(x); m = NaN; else; m = median(x); end; end
